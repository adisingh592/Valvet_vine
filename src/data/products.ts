interface ProductInput {
  name: string;
  photo: string;
  category: ProductCategory;
  subcategory: string;
  gender: Gender;
  brand: string;
  price: number;
  originalPrice?: number;
  retailer: RetailerName;
  /** Other retailers and their prices (for the comparison list). */
  alsoAt?: [RetailerName, number][];
  badge?: Product["badge"];
  colors: ProductColor[];
  sizes: string[];
  occasions: Occasion[];
  tags?: string[];
  description: string;
  details: string[];
  rating: number;
  reviewCount: number;
  isNew?: boolean;
  popularity: number;
}

function defineProduct(id: number, input: ProductInput): Product {
  const slug = slugify(input.name);
  const offers = [[input.retailer, input.price] as [RetailerName, number], ...(input.alsoAt ?? [])].map(
    ([retailer, price]) => {
      const url = placeholderRetailerUrl(retailer, input.name);
      return { retailer, price, affiliateUrl: url, originalUrl: url };
    },
  );

  const tags = new Set([
    ...(input.tags ?? []),
    ...input.occasions,
    slugify(input.subcategory),
    input.category.toLowerCase(),
    input.gender,
  ]);

  return {
    id,
    slug,
    name: input.name,
    category: input.category,
    subcategory: input.subcategory,
    subcategorySlug: slugify(input.subcategory),
    gender: input.gender,
    price: input.price,
    originalPrice: input.originalPrice,
    currency: "INR",
    image: unsplash(input.photo),
    gallery: galleryFor(input.photo),
    brand: input.brand,
    retailer: input.retailer,
    affiliateUrl: offers[0].affiliateUrl,
    originalUrl: offers[0].originalUrl,
    offers,
    badge: input.badge,
    colors: input.colors,
    sizes: input.sizes,
    tags: [...tags],
    occasions: input.occasions,
    description: input.description,
    details: input.details,
    rating: input.rating,
    reviewCount: input.reviewCount,
    isNew: input.isNew,
    popularity: input.popularity,
  };
}

